const DEFAULT_REFERENCE =
  "Conteúdo revisado com base em diretrizes GOLD, GINA, PCDT de Tabagismo/Asma e abordagem clássica de tosse crônica.";

function makeQuestion({
  number,
  topic,
  statement,
  correctAnswers,
  alternatives,
  imageUrl,
  questionType,
  difficulty = "médio",
  summary,
  memoryTip,
  trap,
  reference = DEFAULT_REFERENCE,
}) {
  const normalizedCorrectAnswers = Array.isArray(correctAnswers)
    ? correctAnswers.map((answer) => answer.toUpperCase())
    : [correctAnswers.toUpperCase()];
  const normalizedQuestionType = questionType ||
    (normalizedCorrectAnswers.length > 1 ? "multiple" : "single");

  return {
    topic,
    difficulty,
    statement: `${number}) ${statement}`,
    questionType: normalizedQuestionType,
    correctAnswer: normalizedQuestionType === "single" ? normalizedCorrectAnswers[0] : undefined,
    correctAnswers: normalizedCorrectAnswers,
    alternatives: Object.entries(alternatives).map(([letter, value]) => ({
      letter,
      text: value[0],
      explanation: value[1],
    })),
    imageUrl: imageUrl || null,
    generalComment: `${normalizedCorrectAnswers.length > 1 ? "Respostas corretas" : "Resposta correta"}: ${normalizedCorrectAnswers.join(", ")}. ${summary || ""}`.trim(),
    summary: summary || null,
    memoryTip: memoryTip || null,
    trap: trap || null,
    reference,
  };
}

